import { expect, test } from "@playwright/test"

test.use({ storageState: { cookies: [], origins: [] } })

test("注册、刷新、退出、登录与独立空间", async ({ page }) => {
  const suffix = Date.now()
  const first = `auth-first-${suffix}`
  const second = `auth-second-${suffix}`
  await page.goto("/experiments")
  await expect(page.getByRole("heading", { name: "登录你的研究空间" })).toBeVisible()
  expect((await page.request.get("/api/compounds")).status()).toBe(401)
  await page.getByRole("button", { name: "还没有账号？创建账号" }).click()
  await page.getByLabel("姓名或昵称").fill("第一位研究者")
  await page.getByLabel("账号", { exact: true }).fill(first)
  await page.getByLabel("密码", { exact: true }).fill("first-password-long")
  await page.getByLabel("确认密码", { exact: true }).fill("first-password-long")
  await page.getByRole("button", { name: "注册并进入" }).click()
  await expect(page.getByRole("heading", { name: "实验记录本" })).toBeVisible()
  const compoundResponse = await page.request.post("/api/compounds", { data: { name: `私有化合物${suffix}` } })
  expect(compoundResponse.status()).toBe(201)
  const compound = await compoundResponse.json()
  await page.reload()
  await expect(page.getByRole("heading", { name: "实验记录本" })).toBeVisible()
  const session = (await page.context().cookies()).find(cookie => cookie.name === "rdms_session")!
  expect(session.httpOnly).toBe(true)
  expect(session.sameSite).toBe("Strict")
  await page.getByRole("button", { name: "退出登录" }).click()
  await expect(page.getByRole("heading", { name: "登录你的研究空间" })).toBeVisible()
  expect((await page.request.get(`/api/compounds/${compound.id}`)).status()).toBe(401)

  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole("button", { name: "还没有账号？创建账号" }).click()
  await page.getByLabel("姓名或昵称").fill("第二位研究者")
  await page.getByLabel("账号", { exact: true }).fill(second)
  await page.getByLabel("密码", { exact: true }).fill("second-password-long")
  await page.getByLabel("确认密码", { exact: true }).fill("second-password-long")
  await page.screenshot({ path: "test-results/auth-register-mobile.png", fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole("button", { name: "注册并进入" }).click()
  await expect(page.getByRole("link", { name: "进入实验室" })).toBeVisible()
  expect((await page.request.get("/api/compounds")).status()).toBe(200)
  expect((await (await page.request.get("/api/compounds")).json()).total).toBe(0)
  expect((await page.request.get(`/api/compounds/${compound.id}`)).status()).toBe(404)

  await page.setViewportSize({ width: 1280, height: 800 })
  await page.getByRole("button", { name: "退出登录" }).click()
  await page.getByLabel("账号", { exact: true }).fill(first)
  await page.getByLabel("密码", { exact: true }).fill("wrong-password-long")
  await page.getByRole("button", { name: "登录", exact: true }).click()
  await expect(page.getByRole("alert")).toHaveText("账号或密码错误")
  await page.getByLabel("密码", { exact: true }).fill("first-password-long")
  await page.getByRole("button", { name: "登录", exact: true }).click()
  await expect(page.getByRole("button", { name: "退出登录" })).toBeVisible()
  expect((await page.request.get(`/api/compounds/${compound.id}`)).status()).toBe(200)
  await page.getByRole("link", { name: "设置", exact: true }).click()
  await page.getByLabel("当前密码").fill("first-password-long")
  await page.getByLabel("新密码", { exact: true }).fill("replacement-password-long")
  await page.getByLabel("确认新密码").fill("replacement-password-long")
  await page.getByRole("button", { name: "修改密码" }).click()
  await expect(page.getByText("密码已修改，其他设备上的登录已失效。")).toBeVisible()
})
