import { expect, test } from "@playwright/test"

test.use({ storageState: { cookies: [], origins: [] } })

test("注册、刷新、退出、登录与独立空间", async ({ page }) => {
  const suffix = Date.now()
  const first = `auth-first-${suffix}`
  const second = `auth-second-${suffix}`
  await page.goto("/experiments")
  await expect(page.getByRole("heading", { name: "登录你的研究空间" })).toBeVisible()
  expect((await page.request.get("/api/compounds")).status()).toBe(401)
  await page.getByRole("button", { name: "还没有账号？创建账号" }).click()
  await page.getByLabel("姓名或昵称").fill("第一位研究者")
  await page.getByLabel("账号", { exact: true }).fill(first)
  await page.getByLabel("密码", { exact: true }).fill("first-password-long")
  await page.getByLabel("确认密码", { exact: true }).fill("first-password-long")
  await page.getByRole("button", { name: "注册并进入" }).click()
  await expect(page.getByRole("heading", { name: "实验记录本" })).toBeVisible()
  const compoundResponse = await page.request.post("/api/compounds", { data: { name: `私有化合物${suffix}` } })
  expect(compoundResponse.status()).toBe(201)
  const compound = await compoundResponse.json()
  await page.reload()
  await expect(page.getByRole("heading", { name: "实验记录本" })).toBeVisible()
  const session = (await page.context().cookies()).find(cookie => cookie.name === "rdms_session")!
  expect(session.httpOnly).toBe(true)
  expect(session.sameSite).toBe("Strict")
  await page.getByRole("button", { name: /^账号菜单：/ }).click()
  await page.getByRole("menuitem", { name: "退出登录" }).click()
  await expect(page.getByRole("heading", { name: "登录你的研究空间" })).toBeVisible()
  expect((await page.request.get(`/api/compounds/${compound.id}`)).status()).toBe(401)

  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole("button", { name: "还没有账号？创建账号" }).click()
  await page.getByLabel("姓名或昵称").fill("第二位研究者")
  await page.getByLabel("账号", { exact: true }).fill(second)
  await page.getByLabel("密码", { exact: true }).fill("second-password-long")
  await page.getByLabel("确认密码", { exact: true }).fill("second-password-long")
  await page.screenshot({ path: "test-results/auth-register-mobile.png", fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole("button", { name: "注册并进入" }).click()
  await expect(page.getByRole("link", { name: "进入实验室" })).toBeVisible()
  expect((await page.request.get("/api/compounds")).status()).toBe(200)
  expect((await (await page.request.get("/api/compounds")).json()).total).toBe(0)
  expect((await page.request.get(`/api/compounds/${compound.id}`)).status()).toBe(404)

  await page.setViewportSize({ width: 1280, height: 800 })
  await page.getByRole("button", { name: /^账号菜单：/ }).click()
  await page.getByRole("menuitem", { name: "退出登录" }).click()
  await page.getByLabel("账号", { exact: true }).fill(first)
  await page.getByLabel("密码", { exact: true }).fill("wrong-password-long")
  await page.getByRole("button", { name: "登录", exact: true }).click()
  await expect(page.getByRole("alert")).toHaveText("账号或密码错误")
  await page.getByLabel("密码", { exact: true }).fill("first-password-long")
  await page.getByRole("button", { name: "登录", exact: true }).click()
  await expect(page.getByRole("button", { name: /^账号菜单：/ })).toBeVisible()
  expect((await page.request.get(`/api/compounds/${compound.id}`)).status()).toBe(200)
  await page.getByRole("link", { name: "设置", exact: true }).click()
  await expect(page.getByLabel("当前密码")).toHaveCount(0)
  await page.getByRole("button", { name: /^账号菜单：/ }).click()
  await page.getByRole("menuitem", { name: "修改密码" }).click()
  await page.getByLabel("当前密码").fill("first-password-long")
  await page.getByLabel("新密码", { exact: true }).fill("replacement-password-long")
  await page.getByLabel("确认新密码").fill("replacement-password-long")
  await page.getByRole("button", { name: "保存新密码" }).click()
  await expect(page.getByText("密码已修改，其他设备上的登录已失效。")).toBeVisible()
})


test("账号菜单键盘操作与密码弹窗适配桌面、深色和窄屏", async ({ page }) => {
  const registered = await page.request.post("/api/auth/register", { data: { username: `menu-${Date.now()}`, password: "menu-password-long", display_name: "一位名字很长的研究人员" } })
  expect(registered.status()).toBe(201)
  await page.goto("/")
  const trigger = page.getByRole("button", { name: /^账号菜单：/ })
  await expect(trigger).toBeVisible()
  await trigger.focus()
  await page.keyboard.press("ArrowDown")
  await expect(page.getByRole("menuitem", { name: "修改密码" })).toBeFocused()
  await page.keyboard.press("ArrowDown")
  await expect(page.getByRole("menuitem", { name: "退出登录" })).toBeFocused()
  await page.keyboard.press("Escape")
  await expect(page.getByRole("menu")).toHaveCount(0)
  await expect(trigger).toBeFocused()
  await trigger.click()
  await page.screenshot({ path: "test-results/account-menu-desktop.png", fullPage: true })
  await page.getByRole("textbox", { name: "全局搜索" }).click()
  await expect(page.getByRole("menu")).toHaveCount(0)
  for (const [width, theme] of [[1280, "light"], [1280, "dark"], [390, "light"]] as const) {
    await page.setViewportSize({ width, height: 844 })
    await page.evaluate(value => document.documentElement.dataset.theme = value, theme)
    await trigger.click()
    const bounds = (await page.getByRole("menu").boundingBox())!
    expect(bounds.x).toBeGreaterThanOrEqual(0)
    expect(bounds.y).toBeGreaterThanOrEqual(0)
    expect(bounds.x + bounds.width).toBeLessThanOrEqual(width)
    await page.getByRole("menuitem", { name: "修改密码" }).click()
    const dialog = page.getByRole("dialog", { name: "修改密码" })
    await expect(dialog).toBeVisible()
    expect((await dialog.getByRole("button", { name: "关闭", exact: true }).boundingBox())!.height).toBeLessThanOrEqual(48)
    await expect(dialog.getByLabel("当前密码")).toBeFocused()
    if (width === 1280 && theme === "light") {
      await page.setViewportSize({ width: 390, height: 844 })
      await expect(dialog).toBeVisible()
    expect((await dialog.getByRole("button", { name: "关闭", exact: true }).boundingBox())!.height).toBeLessThanOrEqual(48)
      await page.setViewportSize({ width, height: 844 })
    }
    await dialog.getByLabel("当前密码").fill("menu-password-long")
    await dialog.getByLabel("新密码", { exact: true }).fill("new-password-long")
    await dialog.getByLabel("确认新密码").fill("mismatched-password")
    await dialog.getByRole("button", { name: "保存新密码" }).click()
    await expect(dialog.getByRole("alert")).toHaveText("两次输入的新密码不一致")
    await page.screenshot({ path: `test-results/account-password-${width}-${theme}.png`, fullPage: true })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.keyboard.press("Escape")
    await expect(dialog).toHaveCount(0)
    await expect(trigger).toBeFocused()
  }
  // Closing discards the password fields; reopening must not retain secrets.
  await trigger.click()
  await page.getByRole("menuitem", { name: "修改密码" }).click()
  await expect(page.getByLabel("当前密码")).toHaveValue("")
  await page.getByRole("button", { name: "取消", exact: true }).click()
})
