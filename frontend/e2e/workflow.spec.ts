test("基础记录位于反应上方且双方各自保存并保留未保存输入", async ({ page, request }) => {
  const tag = await (await request.post("/api/tags", { data: { name: "保留历史实验标签" } })).json()
  const experiment = await (await request.post("/api/experiments", { data: { title: "独立保存验证", date: "2026-10-11", objective: "原目的", procedure: "旧操作", observation: "旧观察", result: "旧结果", conclusion: "旧结论", tag_ids: [tag.id] } })).json()
  const reaction = await (await request.post(`/api/experiments/${experiment.id}/reactions`, { data: { reaction_name: "独立反应", atmosphere: "Air" } })).json()
  await page.goto(`/experiments/${experiment.id}`)
  const basic = page.getByRole("form", { name: "实验基础记录", exact: true })
  const card = page.getByRole("article")
  await expect(card.getByLabel("气氛")).toHaveValue("Air")
  expect(await basic.evaluate(element => Boolean(element.compareDocumentPosition(document.querySelector('[aria-label="反应记录"]')!) & Node.DOCUMENT_POSITION_FOLLOWING))).toBe(true)
  await expect(basic.getByLabel("实验备注")).not.toBeVisible()
  await basic.getByText("备注", { exact: true }).click()
  await expect(basic.getByLabel("实验备注")).toHaveValue("操作：\n旧操作\n\n观察：\n旧观察\n\n结果：\n旧结果\n\n结论：\n旧结论")
  await basic.getByLabel("实验备注").fill("统一备注内容")
  await basic.getByLabel("目的").fill("未保存基础记录")
  await card.getByLabel("气氛").fill("N2")
  await card.getByRole("button", { name: "保存反应", exact: true }).click()
  await expect(card.getByText("反应已保存", { exact: true })).toBeVisible()
  expect((await (await request.get(`/api/experiments/${experiment.id}`)).json()).objective).toBe("原目的")
  await expect(basic.getByLabel("目的")).toHaveValue("未保存基础记录")
  await card.getByLabel("气氛").fill("Ar")
  await basic.getByRole("button", { name: "保存基础记录", exact: true }).click()
  await expect(basic.getByRole("status")).toHaveText("已保存")
  await expect(basic.getByText("标签", { exact: true })).toHaveCount(0)
  expect((await (await request.get(`/api/experiments/${experiment.id}`)).json())).toMatchObject({ tags: experiment.tags, notes: "统一备注内容", procedure: "旧操作", observation: "旧观察", result: "旧结果", conclusion: "旧结论" })
  expect((await (await request.get(`/api/reactions/${reaction.id}`)).json()).atmosphere).toBe("N2")
  await expect(card.getByLabel("气氛")).toHaveValue("Ar")
  await page.screenshot({ path: "test-results/experiment-basic-first.png", fullPage: true })
  await page.reload()
  await basic.getByText("备注", { exact: true }).click()
  await expect(basic.getByLabel("实验备注")).toHaveValue("统一备注内容")
})
