test("实验与化合物可以不经总览直接双向切换", async ({ page }) => {
  for (const first of ["实验", "化合物"] as const) {
    const firstPath = first === "实验" ? "/experiments" : "/compounds"
    const second = first === "实验" ? "化合物" : "实验"
    const secondPath = second === "实验" ? "/experiments" : "/compounds"
    await page.goto(firstPath)
    await expect(page.getByRole("heading", { name: first === "实验" ? "实验记录" : "化合物" })).toBeVisible()
    for (const [label, path] of [[second, secondPath], [first, firstPath]] as const) {
      const responsePromise = page.waitForResponse(response => response.url().includes(`/api${path}?`))
      await page.getByRole("navigation", { name: "主导航" }).getByRole("link", { name: label }).click()
      const response = await responsePromise
      expect(response.status()).toBe(200)
      await expect(page.getByRole("heading", { name: label === "实验" ? "实验记录" : "化合物" })).toBeVisible()
      await expect(page.getByText("正在载入记录…")).toBeHidden()
    }
  }
})

