import { expect, test, type Page } from "@playwright/test"
import { readFile } from "node:fs/promises"

const file = process.env.RDMS_DEMO_URL ?? "file:///demo/dist/RDMS-Demo.html"
async function navigate(page: Page, path: string) {
  await page.evaluate(path => { location.hash = path }, path)
}
const issues = new WeakMap<Page, { errors: string[]; network: string[] }>()
test.afterEach(async ({ page }) => {
  expect(issues.get(page)?.errors).toEqual([])
  expect(issues.get(page)?.network).toEqual([])
})
test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => {
    // Make persistence a hard error, including preferences.
    for (const name of ["localStorage", "sessionStorage", "indexedDB", "caches"] as const) Object.defineProperty(window, name, { get() { throw new Error(`Persistence used: ${name}`) } })
  })
  const errors: string[] = []
  const network: string[] = []
  issues.set(page, { errors, network })
  page.on("pageerror", error => errors.push(error.message))
  page.on("request", request => { if (/^https?:/.test(request.url())) network.push(request.url()) })
  await page.goto(file)
})

test("single file runs offline, preserves the real interface, and resets on reload", async ({ page }) => {
  const errors: string[] = []
  const network: string[] = []
  page.on("pageerror", error => errors.push(error.message))
  page.on("request", request => { if (/^https?:/.test(request.url())) network.push(request.url()) })
  await expect(page.getByRole("heading", { name: /研究数据.*管理系统/ })).toBeVisible()
  await expect(page.getByText("登录你的研究空间")).toHaveCount(0)
  await expect(page.locator(".sidebar nav a")).toHaveCount(7)
  await navigate(page, "/experiments/aspirin-synthesis")
  await expect(page.getByRole("heading", { name: "阿司匹林合成与重结晶", exact: true })).toBeVisible()
  await expect(page.getByRole("heading", { name: "投料", exact: true })).toBeVisible()
  await expect(page.locator(".reaction-overview img")).toHaveCount(2)
  expect(await page.locator("img").evaluateAll(images => images.every(image => image.complete && image.naturalWidth > 0))).toBe(true)
  await page.getByLabel("标题 *", { exact: true }).fill("本次修改")
  await page.getByRole("button", { name: "保存基础记录", exact: true }).click()
  await expect(page.getByRole("heading", { name: "本次修改", exact: true })).toBeVisible()
  await navigate(page, "/compounds")
  await expect(page.getByRole("heading", { name: "化合物", exact: true })).toBeVisible()
  await navigate(page, "/experiments/aspirin-synthesis")
  await expect(page.getByLabel("标题 *", { exact: true })).toHaveValue("本次修改")
  await page.reload()
  await expect(page.getByLabel("标题 *", { exact: true })).toHaveValue("阿司匹林合成与重结晶")
  expect(errors).toEqual([])
  expect(network).toEqual([])
})

