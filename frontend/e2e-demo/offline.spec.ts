test("uploads and downloads keep exact bytes, summary includes saved data", async ({ page }) => {
  await navigate(page, "/experiments/aspirin-synthesis")
  await page.getByText("上传文件", { exact: true }).click()
  const bytes = Buffer.from("演示附件\nOnly in memory\n")
  await page.getByLabel("选择原始文件").setInputFiles({ name: "现场记录.txt", mimeType: "text/plain", buffer: bytes })
  await page.getByRole("button", { name: "上传 1 个文件", exact: true }).click()
  const row = page.getByRole("row").filter({ hasText: "现场记录.txt" })
  await expect(row).toBeVisible()
  const downloadEvent = page.waitForEvent("download")
  await row.getByRole("link", { name: "下载", exact: true }).click()
  const download = await downloadEvent
  expect(await readFile((await download.path())!)).toEqual(bytes)
  await page.getByRole("button", { name: "生成摘要", exact: true }).click()
  await expect(page.locator(".summary-preview")).toContainText("现场记录.txt")
  await expect(page.locator(".summary-preview")).toContainText("2-acetyloxybenzoic acid")
  const summaryEvent = page.waitForEvent("download")
  await page.getByRole("button", { name: "下载 Markdown", exact: true }).click()
  expect((await summaryEvent).suggestedFilename()).toBe("NB001-0001-summary.md")
})

